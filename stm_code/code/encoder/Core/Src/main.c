/**
  * @brief  This function is executed in case of error occurrence.
  * @retval None
  */
void Error_Handler(void)
{
  /* USER CODE BEGIN Error_Handler_Debug */
  /* HAL 초기화/송신 실패 등은 IRQ를 막고 주행·청소를 OFF한 뒤 무한 대기한다.
   * debugger가 여기서 멈췄다면 이 함수 자체보다 호출 직전 HAL 반환값과 주변장치 설정을 확인한다. */
  /* User can add his own implementation to report the HAL error return state */
  __disable_irq();
  Robot_FatalStop();
  /* Keep safety IRQ shutdown. DWT can time the fatal blink without SysTick. */
  if (rgb_gpio_ready)
  {
    uint32_t stamp, half_cycles = SystemCoreClock / 2U;
    uint8_t red_on = 1U;
    RGB_ForceRed();
    CoreDebug->DEMCR |= CoreDebug_DEMCR_TRCENA_Msk;
    DWT->CTRL |= DWT_CTRL_CYCCNTENA_Msk;
    stamp = DWT->CYCCNT;
    while (1)
    {
      /* 래치된 치명 오류: 전원을 끌 때까지 빨간 깜빡임을 유지하도록 워치독 먹이를 계속 준다. */
      Watchdog_Feed();
      uint32_t now = DWT->CYCCNT;
      /* Invalid clock information: stay red instead of flashing at an unsafe rate. */
      if (half_cycles != 0U && (uint32_t)(now - stamp) >= half_cycles)
      {
        stamp = now;
        red_on ^= 1U;
        if (red_on) RGB_ForceRed(); else RGB_ForceOff();
      }
    }
  }
  while (1)
  {
    Watchdog_Feed();
  }
  /* USER CODE END Error_Handler_Debug */
}
